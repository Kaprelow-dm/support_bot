import pytest
from main import get_answer

# Список тестов: (запрос, ожидаемая подстрока в ответе)
TEST_CASES = [
    # Точные попадания
    ("доставка", "Доставка по Москве"),
    ("оплата", "Оплата картой"),
    ("гарантия", "Гарантия на товар"),
    
    # Опечатки и сленг (fuzzy matching)
    ("скока стоит", "Цена зависит"),
    ("че по цене", "Цена зависит"),
    ("привезти надо", "Доставка по Москве"),
    
    # Мультикатегории
    ("Сколько стоит доставка", "Доставка по Москве"), # Должен выдать оба, но проверим хотя бы один
    ("Сколько стоит доставка", "Цена зависит"),
    
    # Полный неадекват
    ("Здарова", "Не понял вопрос"),
    ("Что там у нас сегодня?", "Не понял вопрос"),
]

@pytest.mark.parametrize("query, expected_substring", TEST_CASES)
def test_get_answer(query, expected_substring):
    """Проверяем, что бот возвращает правильный ответ (или его часть) на запрос."""
    response = get_answer(query)
    
    # Утверждаем, что ожидаемая подстрока есть в ответе
    assert expected_substring in response, f"❌ Бот не понял '{query}'. Ответ был: '{response}'"

def test_max_three_categories():
    """Проверяем, что бот не выдает больше 3-х тем."""
    # Запрос, который содержит все 5 категорий
    query = "Доставка оплата возврат цена ассортимент"
    response = get_answer(query)
    
    # Считаем, сколько маркеров списка (🔹) в ответе
    count = response.count("🔹")
    assert count <= 3, f"❌ Бот выдал больше 3 тем: {count}"

def test_unknown_query():
    """Проверяем, что на полный бред бот отвечает отказом."""
    query = "абракадабра"
    response = get_answer(query)
    assert "Не понял вопрос" in response